// The Kotlin half of rustls-platform-verifier (certificate checks for
// reqwest), at exactly the version of its Rust crate in Cargo.lock.
repositories {
    maven {
        url = uri("https://github.com/rustls/rustls-platform-verifier/raw/maven-archive/android-release-support/maven/")
    }
}

val rustlsPlatformVerifierVersion: String = run {
    val crate = "rustls-platform-verifier-android"
    val lines = rootProject.file("../../../../../Cargo.lock").readLines()
    val index = lines.indexOfFirst { it.trim() == "name = \"$crate\"" }
    require(index >= 0) { "$crate not found in Cargo.lock" }
    Regex("\"([^\"]+)\"").find(lines[index + 1])!!.groupValues[1]
}

