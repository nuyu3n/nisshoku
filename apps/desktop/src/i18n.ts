export type Language = "ja" | "en";
const dicts: Record<Language, Dict> = { ja, en };

export function lang(): Language {
  return useStore.getState().prefs.language;
}

/** A string in the current language, with `{name}` placeholders filled in. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  // English singulars: `key.one` when n is 1 ("1 note").
  const one = vars?.n === 1 ? dicts[lang()][`${key}.one`] : undefined;
  let s = one ?? dicts[lang()][key] ?? ja[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** `t` for components: re-renders them when the language changes. */
export function useT(): typeof t {
  useStore((s) => s.prefs.language);
  return t;
}
